CREATE TABLE policy (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(customer_id) ON DELETE CASCADE,
    policy_identifier VARCHAR(60) NOT NULL UNIQUE,
    product_name VARCHAR(160) NOT NULL,
    policy_type VARCHAR(40) NOT NULL,
    term_months INTEGER NOT NULL CHECK (term_months > 0),
    start_date DATE NOT NULL,
    maturity_date DATE NOT NULL,
    premium_frequency VARCHAR(30) NOT NULL,
    premium_amount DECIMAL(14, 2) NOT NULL CHECK (premium_amount >= 0),
    sum_insured DECIMAL(16, 2) NOT NULL CHECK (sum_insured >= 0),
    status VARCHAR(30) NOT NULL
);

CREATE INDEX idx_policy_customer_identifier ON policy (customer_id, policy_identifier);

